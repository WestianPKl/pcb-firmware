void ssd1306_init(void)
{
    static const uint8_t init_sequence[] = {
        SSD1306_CTRL_CMD,
        0xAE,
        0xD5, 0x80,
        0xA8, 0x3F,
        0xD3, 0x00,
        0x40,
        0x8D, 0x14,
        0x20, 0x00,
        0xA1,
        0xC8,
        0xDA, 0x12,
        0x81, 0xCF,
        0xD9, 0xF1,
        0xDB, 0x40,
        0xA4,
        0xA6,
        0xAF
    };

    i2c2_write(SSD1306_ADDR, init_sequence, sizeof(init_sequence));
}

void ssd1306_send_command(uint8_t command)
{
    uint8_t data[2] = {SSD1306_CTRL_CMD, command};
    i2c2_write(SSD1306_ADDR, data, sizeof(data));
}

void ssd1306_send_data(const uint8_t *data, size_t length)
{
    uint8_t buffer[255];

    while (length > 0U) {
        size_t chunk = (length > 254U) ? 254U : length;

        buffer[0] = SSD1306_CTRL_DATA;
        memcpy(&buffer[1], data, chunk);
        i2c2_write(SSD1306_ADDR, buffer, (uint16_t)(chunk + 1U));

        data += chunk;
        length -= chunk;
    }
}

void ssd1306_clear_display(void)
{
    static const uint8_t zeros[SSD1306_WIDTH] = {0};

    ssd1306_set_cursor(0U, 0U);
    for (uint8_t page = 0U; page < SSD1306_PAGES; page++) {
        ssd1306_send_data(zeros, sizeof(zeros));
    }
}

void ssd1306_set_cursor(uint8_t col, uint8_t page)
{
    ssd1306_send_command(0x21);
    ssd1306_send_command(col);
    ssd1306_send_command(SSD1306_WIDTH - 1U);

    ssd1306_send_command(0x22);
    ssd1306_send_command(page);
    ssd1306_send_command(SSD1306_PAGES - 1U);
}

void ssd1306_display_text(const char *text, uint8_t col, uint8_t page)
{
    uint8_t glyph[SSD1306_CHAR_WIDTH];

    ssd1306_set_cursor(col, page);
    while (*text) {
        char c = *text++;
        if (c < 0x20 || c > 0x7E) {
            c = ' ';
        }

        memcpy(glyph, font5x7[c - 0x20], SSD1306_FONT_WIDTH);
        glyph[SSD1306_FONT_WIDTH] = 0x00;
        ssd1306_send_data(glyph, sizeof(glyph));
    }
}
